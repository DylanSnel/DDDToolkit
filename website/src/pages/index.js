// One Dark in both colour modes: the code windows are dark whatever the page is.
function Code({ code, className }) {
  return (
    <Highlight theme={themes.oneDark} code={code} language="csharp">
      {({ tokens, getLineProps, getTokenProps }) => (
        <pre className={clsx(styles.code, className)}>
          {tokens.map((line, i) => (
            <div key={i} {...getLineProps({ line })}>
              {line.map((token, key) => (
                <span key={key} {...getTokenProps({ token })} />
              ))}
            </div>
          ))}
        </pre>
      )}
    </Highlight>
  );
}

