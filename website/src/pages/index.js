function Explorer() {
  const [selected, setSelected] = useState(() => sample.files.find((file) => file.name === 'Order.g.cs'));
  const generators = [...new Set(sample.files.map((file) => file.package))];
  // The hero links here; registering the anchor is what lets the build check that link.
  useBrokenLinks().collectAnchor('generated');

  return (
    <section id="generated" className={clsx(styles.section, styles.band)}>
      <div className="container">
        <p className={styles.eyebrow}>What gets generated</p>
        <Heading as="h2" className={styles.sectionTitle}>
          {written} lines in, {generatedLines.toLocaleString('en')} lines out
        </Heading>
        <p className={styles.sectionLead}>
          An order, its lines, an address and one event. Pick a file to see what the generators wrote for it. This is their real
          output for these four files, with only the <code>global::</code> prefixes taken out.
        </p>
        <div className={styles.explorer}>
          <nav className={styles.files} aria-label="Files">
            <p className={styles.filesHeading}>You write</p>
            {sample.inputs.map((file) => (
              <FileButton key={file.name} file={file} active={selected === file} onSelect={setSelected} />
            ))}
            {generators.map((name) => (
              <div key={name}>
                <p className={styles.filesHeading}>
                  Generated by <code>{name}</code>
                </p>
                {sample.files
                  .filter((file) => file.package === name)
                  .map((file) => (
                    <FileButton key={file.name} file={file} active={selected === file} onSelect={setSelected} />
                  ))}
              </div>
            ))}
          </nav>
          <div className={styles.viewer}>
            <p className={styles.explanation}>{explanations[selected.name]}</p>
            <Window title={`${selected.name} · ${selected.lines} lines`} className={styles.viewerWindow}>
              <Code code={selected.code} className={styles.viewerCode} />
            </Window>
          </div>
        </div>
        <p className={styles.explorerFoot}>
          See it in your own project with go to definition on any generated member, or on disk with{' '}
          <code>EmitCompilerGeneratedFiles</code>. <Link to="/docs/generated-code">What each attribute generates →</Link>
        </p>
      </div>
    </section>
  );
}

