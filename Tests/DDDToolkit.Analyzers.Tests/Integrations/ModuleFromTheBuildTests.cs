    [Fact]
    public void The_projects_events_are_named_after_the_module_as_the_runtime_names_them()
    {
        // The generator that names the events cannot see the attribute written beside it; it reads the build's word,
        // and the runtime reads the attribute. The two have to come to the same name, or a stored event is lost.
        var result = Domain().WithModuleFromTheBuild("Ordering").RunCore();

        result.ShouldContain("EventNames", "public static class OrderingEventNames");
        result.ShouldContain("EventNames", "public const string OrderPlaced = \"ordering.order-placed\";");

        var emitted = result.Emit();
        var constant = (string)emitted.Type("Acme.Ordering.Domain.OrderingEventNames").GetField("OrderPlaced")!.GetRawConstantValue()!;
        constant.Should().Be(DomainEventName.Of(emitted.Type("Acme.Ordering.Domain.OrderPlaced")));
    }

