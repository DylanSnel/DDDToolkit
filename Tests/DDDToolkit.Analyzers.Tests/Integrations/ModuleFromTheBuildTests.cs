    [Theory]
    [InlineData("the build")]
    [InlineData("an AssemblyAttribute item")]
    public void A_template_the_module_declares_nowhere_is_DDD00049_at_the_project_file(string declaredBy)
    {
        // The project has no [assembly: Module] for the diagnostic to point at, or has one in the AssemblyInfo.cs
        // the SDK writes into obj/; either way the file somebody edits to declare the module is the project file.
        var host = GeneratorTestHost.Create("namespace Shop.Infrastructure;\n\npublic static class Nothing;", "Nothing.cs")
            .WithAssemblyName("Shop.Infrastructure")
            .WithReferencedAssembly(TemplateEntityTests.Package, "Sample.Tenancy")
            .WithReferencedProject("Shop.Domain", project => project
                .WithModuleFromTheBuild("Shop")
                .WithSource(TemplateEntityTests.Ids.Replace("namespace Sample;", "namespace Shop.Domain;", StringComparison.Ordinal), "Ids.cs")
                .WithSource(
                    """
                    namespace Shop.Domain;

                    [Sample.Tenancy.TenantAggregate<TenantId>]
                    public sealed partial class OnlyTenant
                    {
                        public OnlyTenant(TenantId id, string name) : base(id, name) { }
                    }
                    """,
                    "Classes.cs"))
            .WithReferencedAssembly(TemplateRegistrationTests.Registrations, "Sample.Tenancy.Registrations");
        host = declaredBy == "the build"
            ? host.WithModuleFromTheBuild("Shop")
            : host.WithModule("Shop").WithSource(
                """
                //------------------------------------------------------------------------------
                // <auto-generated>
                //     This code was generated by a tool.
                // </auto-generated>
                //------------------------------------------------------------------------------

                [assembly: DDDToolkit.Abstractions.Attributes.ModuleAttribute("Shop")]
                """,
                "obj/Debug/net10.0/Shop.Infrastructure.AssemblyInfo.cs");

        var result = host.RunCore();

        var reported = result.ReportedDiagnostics.Where(diagnostic => diagnostic.Id == "DDD00049").ToList();
        reported.Should().HaveCount(2, "the organization and the unit are both missing");
        reported.Should().OnlyContain(diagnostic => diagnostic.Location.GetLineSpan().Path == host.ProjectFile, "the project file is where the module is declared");
        result.CompilationErrors.Should().BeEmpty();
    }

